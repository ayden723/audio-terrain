/** Sample an evenly-spaced stop list at v (0..1) into a THREE.Color. */
export function rampColor(stops, v, out) {
  v = v < 0 ? 0 : v > 1 ? 1 : v;
  const seg = stops.length - 1;
  const x = v * seg;
  const i = Math.min(seg - 1, Math.floor(x));
  const f = x - i;
  const a = stops[i], b = stops[i + 1];
  out.setRGB(
    (a[0] + (b[0] - a[0]) * f) / 255,
    (a[1] + (b[1] - a[1]) * f) / 255,
    (a[2] + (b[2] - a[2]) * f) / 255,
    THREE.SRGBColorSpace
  );
  return out;
}
